param([string]$SourceRef = 'd7d4ef4d8334f9e70a75a088cb77804bf81daea4')

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$utf8 = [System.Text.UTF8Encoding]::new($false)
$conditions = @(Get-Content -LiteralPath (Join-Path $PSScriptRoot 'weather_conditions.json') -Raw -Encoding UTF8 | ConvertFrom-Json)
$temporary = Join-Path ([System.IO.Path]::GetTempPath()) ('qweather-icons-' + [guid]::NewGuid().ToString('N'))
[void][System.IO.Directory]::CreateDirectory($temporary)

# 只下载公开图标素材；不访问天气接口，也不读取设备密钥。
$commit = Invoke-RestMethod -Uri "https://api.github.com/repos/qwd/Icons/commits/$SourceRef" -Headers @{'User-Agent'='JD79668-calendar-assets'}
$revision = $commit.sha
$base = "https://raw.githubusercontent.com/qwd/Icons/$revision"
$map = Invoke-RestMethod -Uri "$base/font/qweather-icons.json"
$fontPath = Join-Path $temporary 'qweather-icons.ttf'
Invoke-WebRequest -Uri "$base/font/fonts/qweather-icons.ttf" -OutFile $fontPath -UseBasicParsing

$fontCollection = [System.Drawing.Text.PrivateFontCollection]::new()
$fontCollection.AddFontFile($fontPath)
$font = [System.Drawing.Font]::new($fontCollection.Families[0], 96, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$format = [System.Drawing.StringFormat]::GenericTypographic.Clone()
$format.FormatFlags = $format.FormatFlags -bor [System.Drawing.StringFormatFlags]::NoFontFallback
$cpp = [System.Text.StringBuilder]::new()
[void]$cpp.AppendLine('// Generated by tools/generate_weather_icons.ps1; do not edit bitmap bytes manually.')
[void]$cpp.AppendLine("// QWeather Icons revision: $revision")
[void]$cpp.AppendLine('// Copyright QWeather; CC BY 4.0. See assets/qweather/NOTICE.txt.')
[void]$cpp.AppendLine('const Condition CONDITIONS[] = {')
$colors = @('Color4::Black', 'Color4::White', 'Color4::Yellow', 'Color4::Red')
foreach ($condition in $conditions) {
  $name = ConvertTo-Json -InputObject ([string]$condition.name) -Compress
  $label = ConvertTo-Json -InputObject ([string]$condition.label) -Compress
  [void]$cpp.AppendLine("    {$($condition.code), $name, $label, $($colors[$condition.color])},")
}
[void]$cpp.AppendLine('};')
[void]$cpp.AppendLine('const uint8_t ICON_BITMAPS[][ICON_BYTES] PROGMEM = {')
$browser = [System.Collections.Generic.List[object]]::new()

try {
  foreach ($condition in $conditions) {
    $property = $map.PSObject.Properties[[string]$condition.code]
    if ($null -eq $property) { throw "Official font has no mapping for $($condition.code)." }
    $large = [System.Drawing.Bitmap]::new(160, 160)
    $small = [System.Drawing.Bitmap]::new(30, 30)
    $largeGraphics = [System.Drawing.Graphics]::FromImage($large)
    $smallGraphics = [System.Drawing.Graphics]::FromImage($small)
    try {
      $largeGraphics.Clear([System.Drawing.Color]::White)
      $largeGraphics.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
      $largeGraphics.DrawString([string][char][int]$property.Value, $font, [System.Drawing.Brushes]::Black, [System.Drawing.PointF]::new(16, 16), $format)
      $left = 160; $top = 160; $right = -1; $bottom = -1
      for ($y = 0; $y -lt 160; $y++) {
        for ($x = 0; $x -lt 160; $x++) {
          if ($large.GetPixel($x, $y).R -lt 168) {
            $left = [Math]::Min($left, $x); $right = [Math]::Max($right, $x)
            $top = [Math]::Min($top, $y); $bottom = [Math]::Max($bottom, $y)
          }
        }
      }
      if ($right -lt $left) { throw "Cannot rasterize weather glyph $($condition.code)." }
      $sourceWidth = $right - $left + 1
      $sourceHeight = $bottom - $top + 1
      $scale = [Math]::Min(28.0 / $sourceWidth, 28.0 / $sourceHeight)
      $width = [Math]::Max(1, [int][Math]::Round($sourceWidth * $scale))
      $height = [Math]::Max(1, [int][Math]::Round($sourceHeight * $scale))
      $destination = [System.Drawing.Rectangle]::new([int][Math]::Floor((30 - $width) / 2), [int][Math]::Floor((30 - $height) / 2), $width, $height)
      $smallGraphics.Clear([System.Drawing.Color]::White)
      $smallGraphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
      $smallGraphics.DrawImage($large, $destination, $left, $top, $sourceWidth, $sourceHeight, [System.Drawing.GraphicsUnit]::Pixel)
      $bytes = [byte[]]::new(120)
      for ($y = 0; $y -lt 30; $y++) {
        for ($x = 0; $x -lt 30; $x++) {
          if ($small.GetPixel($x, $y).R -lt 168) {
            $index = $y * 4 + [int][Math]::Floor($x / 8)
            $bytes[$index] = $bytes[$index] -bor (128 -shr ($x % 8))
          }
        }
      }
      [void]$cpp.AppendLine("    { // $($condition.code)")
      for ($offset = 0; $offset -lt 120; $offset += 12) {
        $line = ($bytes[$offset..($offset + 11)] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
        [void]$cpp.AppendLine("        $line,")
      }
      [void]$cpp.AppendLine('    },')
      $hex = ($bytes | ForEach-Object { '{0:x2}' -f $_ }) -join ''
      $browser.Add([ordered]@{code=$condition.code; name=$condition.name; label=$condition.label; color=$condition.color; bitmap=$hex})
    } finally {
      $largeGraphics.Dispose(); $smallGraphics.Dispose()
      $large.Dispose(); $small.Dispose()
    }
  }
} finally {
  $format.Dispose(); $font.Dispose(); $fontCollection.Dispose()
}

[void]$cpp.AppendLine('};')
$catalogue = [ordered]@{
  source='https://github.com/qwd/Icons'; license='CC BY 4.0'; revision=$revision
  size=30; stride=4; icons=$browser.ToArray()
}
# 这里只生成素材文件，不编译固件，也不运行测试或检查。
[System.IO.File]::WriteAllText((Join-Path $root 'src/weather_icon_assets.inc'), $cpp.ToString(), $utf8)
[System.IO.File]::WriteAllText((Join-Path $root 'web/weather-icons.json'), ($catalogue | ConvertTo-Json -Depth 5 -Compress), $utf8)
Write-Output "Generated $($conditions.Count) weather masks and browser catalogue from QWeather $revision."
